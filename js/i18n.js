function getLang() {
  const saved = localStorage.getItem(I18N_KEY);
  return saved === "en" || saved === "sk" ? saved : "sk";
}

function setLang(lang) {
  localStorage.setItem(I18N_KEY, lang);
  applyLang(lang);
}

function t(key, lang = getLang()) {
  return SITE[lang]?.[key] ?? SITE.en[key] ?? key;
}

function applyLang(lang) {
  const dict = SITE[lang] || SITE.sk;
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.getAttribute("data-i18n");
    let value = dict[key];
    if (value == null) return;
    if (key === "footer.copy") value = value.replace("{year}", String(new Date().getFullYear()));
    if (node.dataset.i18nHtml === "true") node.innerHTML = value;
    else node.textContent = value;
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    const key = node.getAttribute("data-i18n-placeholder");
    if (dict[key] != null) node.setAttribute("placeholder", dict[key]);
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((node) => {
    const key = node.getAttribute("data-i18n-aria");
    if (dict[key] != null) node.setAttribute("aria-label", dict[key]);
  });
  const title = dict["meta.title"];
  const desc = dict["meta.desc"];
  if (title) document.title = title;
  const meta = document.querySelector('meta[name="description"]');
  if (meta && desc) meta.setAttribute("content", desc);

  document.querySelectorAll("[data-lang]").forEach((btn) => {
    const active = btn.getAttribute("data-lang") === lang;
    btn.setAttribute("aria-pressed", active ? "true" : "false");
    btn.classList.toggle("is-active", active);
  });

  document.dispatchEvent(new CustomEvent("ih:lang", { detail: { lang } }));
}

function bindLangSwitch() {
  document.querySelectorAll("[data-lang]").forEach((btn) => {
    btn.addEventListener("click", () => setLang(btn.getAttribute("data-lang")));
  });
}

window.IH = { getLang, setLang, t, applyLang, bindLangSwitch, SITE, I18N_KEY, CONTACT_EMAIL };
