function lang() {
  return window.IH?.getLang?.() || "sk";
}

function at(key) {
  const dict = AUDIT[lang()] || AUDIT.en;
  return dict[key] ?? AUDIT.en[key] ?? key;
}

function questions() {
  return (AUDIT[lang()] || AUDIT.en).q;
}

function optionLabel(qid, oid) {
  const q = questions().find((item) => item.id === qid);
  const opt = q?.options.find(([id]) => id === oid);
  return opt?.[1] || oid;
}

